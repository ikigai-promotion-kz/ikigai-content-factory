/** Пресеты, которые не переписывают содержимое кадра — единственные для слайдов с текстом. */
export const SAFE_FOR_TEXT = Object.entries(PRESETS)
  .filter(([, p]) => p.safeForText)
  .map(([key]) => key);

/** Пресет по короткому имени. Бросает, если имени нет — молча брать другой нельзя. */
export function resolvePreset(key) {
  const p = PRESETS[key];
  if (!p) {
    throw new Error(
      `Пресет «${key}» не из нашего среза. Доступны: ${Object.keys(PRESETS).join(', ')}. ` +
      'Полный список 62 пресетов — knowledge/neural-nets/higgsfield-presets-catalog.md, ' +
      'но остальные работают с личностью и кастингом не управляются.'
    );
  }
  return p;
}
